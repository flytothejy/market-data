CREATE TABLE IF NOT EXISTS users (uid TEXT PRIMARY KEY, chat_id INTEGER, tg_name TEXT, mode TEXT DEFAULT 'digest', created INTEGER, linked INTEGER);
CREATE INDEX IF NOT EXISTS users_chat ON users(chat_id);
CREATE TABLE IF NOT EXISTS devices (code_hash TEXT PRIMARY KEY, uid TEXT NOT NULL, created INTEGER, seen INTEGER);
CREATE INDEX IF NOT EXISTS devices_uid ON devices(uid);
CREATE TABLE IF NOT EXISTS tokens (token TEXT PRIMARY KEY, uid TEXT NOT NULL, kind TEXT NOT NULL, exp INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS watch (uid TEXT PRIMARY KEY, data TEXT NOT NULL, u INTEGER NOT NULL);
